    percent_left    DOUBLE PRECISION,
    percent_right   DOUBLE PRECISION,
    flags           VARCHAR(16)  NOT NULL DEFAULT 'NORMAL',
    CONSTRAINT ck_graph_type CHECK (graph_type IN ('NORMAL', 'STACKED', 'PIE', 'EXPLODED')),
    CONSTRAINT ck_graph_flags CHECK (flags IN ('NORMAL', 'PROTOTYPE', 'DISCOVERED'))
);

CREATE TABLE graph_item (
    gitem_id        BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    graph_id        BIGINT       NOT NULL REFERENCES graph(graph_id) ON DELETE CASCADE,
    item_id         BIGINT       NOT NULL REFERENCES item(item_id) ON DELETE CASCADE,
    sortorder       INTEGER      NOT NULL DEFAULT 0,
    color           VARCHAR(8)   NOT NULL DEFAULT '1A7C11',
    draw_type       VARCHAR(16)  NOT NULL DEFAULT 'LINE',
    y_axis_side     VARCHAR(8)   NOT NULL DEFAULT 'LEFT',
    calc_function   VARCHAR(16)  NOT NULL DEFAULT 'AVG',
    CONSTRAINT ck_gitem_draw CHECK (draw_type IN ('LINE', 'FILLED', 'BOLD_LINE', 'DOT', 'DASHED', 'GRADIENT')),
    CONSTRAINT ck_gitem_axis CHECK (y_axis_side IN ('LEFT', 'RIGHT')),
    CONSTRAINT ck_gitem_calc CHECK (calc_function IN ('MIN', 'AVG', 'MAX', 'ALL', 'LAST'))
);

CREATE INDEX ix_graph_item_graph ON graph_item (graph_id);

-- Network topology maps.
CREATE TABLE network_map (
    map_id          BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    tenant_id       BIGINT       NOT NULL REFERENCES tenant(tenant_id) ON DELETE CASCADE,
    name            VARCHAR(255) NOT NULL,
    width           INTEGER      NOT NULL DEFAULT 1200,
    height          INTEGER      NOT NULL DEFAULT 800,
    background_url  VARCHAR(2048) NOT NULL DEFAULT '',
    owner_user_id   BIGINT       REFERENCES app_user(user_id) ON DELETE SET NULL,
    private         BOOLEAN      NOT NULL DEFAULT FALSE,
    CONSTRAINT uq_map_name UNIQUE (tenant_id, name)
);

CREATE TABLE network_map_element (
    element_id      BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    map_id          BIGINT       NOT NULL REFERENCES network_map(map_id) ON DELETE CASCADE,
    element_type    VARCHAR(16)  NOT NULL DEFAULT 'HOST',
    -- Points at a host, host group, map or trigger depending on element_type.
    element_ref_id  BIGINT,
    label           VARCHAR(2048) NOT NULL DEFAULT '',
    x               INTEGER      NOT NULL DEFAULT 0,
    y               INTEGER      NOT NULL DEFAULT 0,
    icon            VARCHAR(64)  NOT NULL DEFAULT 'server',
    url             VARCHAR(2048) NOT NULL DEFAULT '',
    CONSTRAINT ck_map_element_type CHECK (element_type IN ('HOST', 'HOST_GROUP', 'TRIGGER', 'MAP', 'IMAGE'))
);

CREATE TABLE network_map_link (
    link_id         BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    map_id          BIGINT       NOT NULL REFERENCES network_map(map_id) ON DELETE CASCADE,
    from_element_id BIGINT       NOT NULL REFERENCES network_map_element(element_id) ON DELETE CASCADE,
    to_element_id   BIGINT       NOT NULL REFERENCES network_map_element(element_id) ON DELETE CASCADE,
    label           VARCHAR(2048) NOT NULL DEFAULT '',
    color           VARCHAR(8)   NOT NULL DEFAULT '00CC00',
    draw_type       VARCHAR(16)  NOT NULL DEFAULT 'LINE',
    -- When any of these triggers is in PROBLEM the link is drawn in its colour,
    -- which is what makes a map convey state rather than just topology.
    indicator_trigger_ids BIGINT[] NOT NULL DEFAULT '{}'
);

-- ---------------------------------------------------------------------------
-- Audit
