    pos_y           INTEGER      NOT NULL DEFAULT 0,
    width           INTEGER      NOT NULL DEFAULT 12,
    height          INTEGER      NOT NULL DEFAULT 5,
    config          JSONB        NOT NULL DEFAULT '{}'::jsonb,
    CONSTRAINT ck_widget_type CHECK (type IN
        ('PROBLEMS', 'PROBLEM_SEVERITY', 'GRAPH', 'SVG_GRAPH', 'GAUGE', 'ITEM_VALUE',
         'CLOCK', 'MAP', 'HOST_AVAILABILITY', 'SYSTEM_INFO', 'TOP_HOSTS', 'URL',
         'CAMERA_WALL', 'DISCOVERY_STATUS', 'ACTION_LOG', 'DATA_OVERVIEW')),
    CONSTRAINT ck_widget_geometry CHECK (width > 0 AND height > 0 AND pos_x >= 0 AND pos_y >= 0)
);

CREATE INDEX ix_widget_dashboard ON dashboard_widget (dashboard_id);

CREATE TABLE graph (
    graph_id        BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    tenant_id       BIGINT       NOT NULL REFERENCES tenant(tenant_id) ON DELETE CASCADE,
    name            VARCHAR(255) NOT NULL,
    width           INTEGER      NOT NULL DEFAULT 900,
    height          INTEGER      NOT NULL DEFAULT 200,
    graph_type      VARCHAR(16)  NOT NULL DEFAULT 'NORMAL',
    show_legend     BOOLEAN      NOT NULL DEFAULT TRUE,
    show_working_time BOOLEAN    NOT NULL DEFAULT TRUE,
    y_axis_min      DOUBLE PRECISION,
