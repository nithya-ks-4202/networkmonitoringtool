        ('LOGIN', 'LOGOUT', 'LOGIN_FAILED', 'CREATE', 'UPDATE', 'DELETE', 'EXECUTE', 'ACKNOWLEDGE'))
);

CREATE INDEX ix_audit_clock ON audit_log (tenant_id, clock DESC);
CREATE INDEX ix_audit_resource ON audit_log (resource_type, resource_id, clock DESC);
