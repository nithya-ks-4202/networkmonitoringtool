-- ---------------------------------------------------------------------------
-- Triggers: boolean expressions over collected values that define a problem
-- ---------------------------------------------------------------------------

CREATE TABLE trigger_def (
    trigger_id      BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    tenant_id       BIGINT       NOT NULL REFERENCES tenant(tenant_id) ON DELETE CASCADE,
    host_id         BIGINT       NOT NULL REFERENCES host(host_id) ON DELETE CASCADE,
    description     VARCHAR(1024) NOT NULL,
    expression      TEXT         NOT NULL,
    -- When set, the problem stays open until this expression is true, rather
    -- than until the problem expression goes false. This is what implements
    -- hysteresis and stops alert flapping on a threshold boundary.
    recovery_mode   VARCHAR(24)  NOT NULL DEFAULT 'EXPRESSION',
    recovery_expression TEXT     NOT NULL DEFAULT '',
    severity        VARCHAR(24)  NOT NULL DEFAULT 'NOT_CLASSIFIED',
    status          VARCHAR(16)  NOT NULL DEFAULT 'ENABLED',
    state           VARCHAR(16)  NOT NULL DEFAULT 'NORMAL',
    value           VARCHAR(16)  NOT NULL DEFAULT 'OK',
    error           TEXT         NOT NULL DEFAULT '',
    -- OK events can be generated for every recovery or only for the matching
    -- problem event, which matters when several problems share a trigger.
    correlation_mode VARCHAR(24) NOT NULL DEFAULT 'ALL',
    correlation_tag VARCHAR(255) NOT NULL DEFAULT '',
    -- MULTIPLE lets one trigger hold several simultaneous problems, keyed by
    -- the event name; needed for log and trap driven triggers.
    event_generation VARCHAR(16) NOT NULL DEFAULT 'SINGLE',
    manual_close    BOOLEAN      NOT NULL DEFAULT FALSE,
    url             VARCHAR(2048) NOT NULL DEFAULT '',
    comments        TEXT         NOT NULL DEFAULT '',
    opdata          VARCHAR(1024) NOT NULL DEFAULT '',
    event_name      VARCHAR(1024) NOT NULL DEFAULT '',
    template_trigger_id BIGINT   REFERENCES trigger_def(trigger_id) ON DELETE SET NULL,
    discovered_by_rule_id BIGINT,
    flags           VARCHAR(16)  NOT NULL DEFAULT 'NORMAL',
    last_change_at  TIMESTAMPTZ,
    created_at      TIMESTAMPTZ  NOT NULL DEFAULT now(),
    updated_at      TIMESTAMPTZ  NOT NULL DEFAULT now(),
    CONSTRAINT ck_trigger_severity CHECK (severity IN
        ('NOT_CLASSIFIED', 'INFORMATION', 'WARNING', 'AVERAGE', 'HIGH', 'DISASTER')),
    CONSTRAINT ck_trigger_status CHECK (status IN ('ENABLED', 'DISABLED')),
    CONSTRAINT ck_trigger_state CHECK (state IN ('NORMAL', 'UNKNOWN')),
    CONSTRAINT ck_trigger_value CHECK (value IN ('OK', 'PROBLEM')),
    CONSTRAINT ck_trigger_recovery_mode CHECK (recovery_mode IN
        ('EXPRESSION', 'RECOVERY_EXPRESSION', 'NONE')),
    CONSTRAINT ck_trigger_event_generation CHECK (event_generation IN ('SINGLE', 'MULTIPLE')),
    CONSTRAINT ck_trigger_flags CHECK (flags IN ('NORMAL', 'PROTOTYPE', 'DISCOVERED'))
);

CREATE INDEX ix_trigger_host ON trigger_def (host_id);
CREATE INDEX ix_trigger_status ON trigger_def (tenant_id, status) WHERE status = 'ENABLED';

-- Which items a trigger reads. Maintained by the expression parser so that a
-- new value can find the triggers it must re-evaluate without a table scan.
CREATE TABLE trigger_item (
    trigger_id      BIGINT NOT NULL REFERENCES trigger_def(trigger_id) ON DELETE CASCADE,
    item_id         BIGINT NOT NULL REFERENCES item(item_id) ON DELETE CASCADE,
    PRIMARY KEY (trigger_id, item_id)
);

CREATE INDEX ix_trigger_item_item ON trigger_item (item_id);

-- A trigger with an unresolved dependency does not fire. This is how "the
-- switch is down" suppresses the forty cameras behind it.
CREATE TABLE trigger_dependency (
    trigger_id      BIGINT NOT NULL REFERENCES trigger_def(trigger_id) ON DELETE CASCADE,
    depends_on_trigger_id BIGINT NOT NULL REFERENCES trigger_def(trigger_id) ON DELETE CASCADE,
    PRIMARY KEY (trigger_id, depends_on_trigger_id),
    CONSTRAINT ck_trigger_dep_distinct CHECK (trigger_id <> depends_on_trigger_id)
);

CREATE TABLE trigger_tag (
    tag_id          BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    trigger_id      BIGINT       NOT NULL REFERENCES trigger_def(trigger_id) ON DELETE CASCADE,
    tag             VARCHAR(255) NOT NULL,
    value           VARCHAR(255) NOT NULL DEFAULT '',
    CONSTRAINT uq_trigger_tag UNIQUE (trigger_id, tag, value)
);

-- ---------------------------------------------------------------------------
-- Events and problems
--
-- An event is an immutable fact ("this trigger went to PROBLEM at 09:14").
-- A problem is the mutable open-incident view built from events. Separating
-- them is what allows the problem table to stay small and fast while events
-- accumulate for audit.
-- ---------------------------------------------------------------------------

CREATE TABLE event (
    event_id        BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    tenant_id       BIGINT       NOT NULL REFERENCES tenant(tenant_id) ON DELETE CASCADE,
    source          VARCHAR(24)  NOT NULL DEFAULT 'TRIGGER',
    object_type     VARCHAR(24)  NOT NULL DEFAULT 'TRIGGER',
    object_id       BIGINT       NOT NULL,
    clock           TIMESTAMPTZ  NOT NULL DEFAULT now(),
    value           VARCHAR(16)  NOT NULL,
    severity        VARCHAR(24)  NOT NULL DEFAULT 'NOT_CLASSIFIED',
    name            VARCHAR(2048) NOT NULL DEFAULT '',
    acknowledged    BOOLEAN      NOT NULL DEFAULT FALSE,
    CONSTRAINT ck_event_source CHECK (source IN
        ('TRIGGER', 'DISCOVERY', 'AUTOREGISTRATION', 'INTERNAL', 'SERVICE')),
    CONSTRAINT ck_event_value CHECK (value IN ('OK', 'PROBLEM'))
);

CREATE INDEX ix_event_clock ON event (tenant_id, clock DESC);
CREATE INDEX ix_event_object ON event (object_type, object_id, clock DESC);

CREATE TABLE problem (
    problem_id      BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    tenant_id       BIGINT       NOT NULL REFERENCES tenant(tenant_id) ON DELETE CASCADE,
    event_id        BIGINT       NOT NULL REFERENCES event(event_id) ON DELETE CASCADE,
    source          VARCHAR(24)  NOT NULL DEFAULT 'TRIGGER',
    object_type     VARCHAR(24)  NOT NULL DEFAULT 'TRIGGER',
    object_id       BIGINT       NOT NULL,
    host_id         BIGINT       REFERENCES host(host_id) ON DELETE CASCADE,
    clock           TIMESTAMPTZ  NOT NULL DEFAULT now(),
    name            VARCHAR(2048) NOT NULL DEFAULT '',
    severity        VARCHAR(24)  NOT NULL DEFAULT 'NOT_CLASSIFIED',
    -- Severity can be changed by an operator during triage; the original is
    -- kept so reporting is not rewritten by human action.
    original_severity VARCHAR(24) NOT NULL DEFAULT 'NOT_CLASSIFIED',
    acknowledged    BOOLEAN      NOT NULL DEFAULT FALSE,
    suppressed      BOOLEAN      NOT NULL DEFAULT FALSE,
    suppressed_until TIMESTAMPTZ,
    opdata          VARCHAR(1024) NOT NULL DEFAULT '',
    -- Populated on recovery. A row with r_event_id set is a resolved problem
    -- retained for the problem history view.
    r_event_id      BIGINT       REFERENCES event(event_id) ON DELETE SET NULL,
    resolved_at     TIMESTAMPTZ,
    resolved_by     VARCHAR(128),
    CONSTRAINT uq_problem_event UNIQUE (event_id)
);

CREATE INDEX ix_problem_open ON problem (tenant_id, severity, clock DESC) WHERE r_event_id IS NULL;
CREATE INDEX ix_problem_object ON problem (object_type, object_id) WHERE r_event_id IS NULL;
CREATE INDEX ix_problem_host ON problem (host_id) WHERE r_event_id IS NULL;

CREATE TABLE problem_tag (
    tag_id          BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    problem_id      BIGINT       NOT NULL REFERENCES problem(problem_id) ON DELETE CASCADE,
    tag             VARCHAR(255) NOT NULL,
    value           VARCHAR(255) NOT NULL DEFAULT ''
);

CREATE INDEX ix_problem_tag_lookup ON problem_tag (tag, value);
CREATE INDEX ix_problem_tag_problem ON problem_tag (problem_id);

-- Operator actions on a problem: acknowledge, comment, close, change severity.
CREATE TABLE problem_ack (
    ack_id          BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    problem_id      BIGINT       NOT NULL REFERENCES problem(problem_id) ON DELETE CASCADE,
    user_id         BIGINT       REFERENCES app_user(user_id) ON DELETE SET NULL,
    clock           TIMESTAMPTZ  NOT NULL DEFAULT now(),
    message         TEXT         NOT NULL DEFAULT '',
    -- Bit set of what this action did, kept as explicit columns for clarity.
    action_acknowledge BOOLEAN   NOT NULL DEFAULT FALSE,
    action_unacknowledge BOOLEAN NOT NULL DEFAULT FALSE,
    action_close    BOOLEAN      NOT NULL DEFAULT FALSE,
    action_message  BOOLEAN      NOT NULL DEFAULT FALSE,
    action_severity BOOLEAN      NOT NULL DEFAULT FALSE,
    action_suppress BOOLEAN      NOT NULL DEFAULT FALSE,
    new_severity    VARCHAR(24),
    suppress_until  TIMESTAMPTZ
);

CREATE INDEX ix_problem_ack_problem ON problem_ack (problem_id, clock DESC);
